-- Flow (owner's ask, 2026-11-02): a production pipeline per batch, built on a
-- canvas — steps (fabric/material PO, cutting, job work, stitching, QC,
-- packing, ready stock) joined by connections, each step optionally linked
-- to a real purchase order or job-work order, with files attached to the
-- pipeline or to one step, and reusable templates.
--
--   flow_pipelines    one batch (title, SKU, pieces, size split, due, status)
--   flow_steps        a box on the canvas (kind, who, qty planned/done, status,
--                     x/y, optional po_id / jobwork_order_id)
--   flow_edges        an arrow from one step to the next (optional label)
--   flow_attachments  files in the private flow-files bucket
--   flow_templates    a saved graph to start new pipelines from
--
-- Access: active staff (admin/manager/operator, app_is_staff()) read and
-- write everything; only admin/manager delete a pipeline or a template.
-- flow_create() makes a pipeline + its template steps + connections in one
-- transaction (SECURITY INVOKER, so RLS applies).

create table public.flow_pipelines (
  id uuid primary key default gen_random_uuid(),
  flow_number int generated by default as identity unique,
  title text not null check (btrim(title) <> ''),
  sku text,
  pieces int check (pieces is null or pieces > 0),
  sizes text,
  costing_product_id uuid references public.costing_products(id) on delete set null,
  status text not null default 'planning' check (status in ('planning', 'running', 'done', 'cancelled')),
  due_date date,
  notes text,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index flow_pipelines_status_idx on public.flow_pipelines (status, created_at desc);
create index flow_pipelines_sku_idx on public.flow_pipelines (sku);

create table public.flow_steps (
  id uuid primary key default gen_random_uuid(),
  pipeline_id uuid not null references public.flow_pipelines(id) on delete cascade,
  kind text not null check (kind in ('po', 'cutting', 'jobwork', 'stitching', 'qc', 'packing', 'stock', 'other')),
  title text not null default '',
  assignee text,
  po_id uuid references public.purchase_orders(id) on delete set null,
  jobwork_order_id uuid references public.jobwork_orders(id) on delete set null,
  qty_planned numeric(14,3) check (qty_planned is null or qty_planned >= 0),
  qty_done numeric(14,3) not null default 0 check (qty_done >= 0),
  unit text,
  status text not null default 'planned' check (status in ('planned', 'active', 'done', 'blocked')),
  due_date date,
  notes text,
  x int not null default 0,
  y int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index flow_steps_pipeline_idx on public.flow_steps (pipeline_id);
create index flow_steps_po_idx on public.flow_steps (po_id) where po_id is not null;
create index flow_steps_jw_idx on public.flow_steps (jobwork_order_id) where jobwork_order_id is not null;
create index flow_steps_assignee_idx on public.flow_steps (kind, assignee, status);

create table public.flow_edges (
  id uuid primary key default gen_random_uuid(),
  pipeline_id uuid not null references public.flow_pipelines(id) on delete cascade,
  from_step uuid not null references public.flow_steps(id) on delete cascade,
  to_step uuid not null references public.flow_steps(id) on delete cascade,
  label text,
  created_at timestamptz not null default now(),
  unique (from_step, to_step),
  check (from_step <> to_step)
);
create index flow_edges_pipeline_idx on public.flow_edges (pipeline_id);

create table public.flow_attachments (
  id uuid primary key default gen_random_uuid(),
  pipeline_id uuid not null references public.flow_pipelines(id) on delete cascade,
  step_id uuid references public.flow_steps(id) on delete set null,
  path text not null unique,
  name text not null,
  type text,
  size int,
  uploaded_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index flow_attachments_pipeline_idx on public.flow_attachments (pipeline_id, created_at desc);

create table public.flow_templates (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (btrim(name) <> ''),
  graph jsonb not null,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

-- RLS: staff only; deleting a whole pipeline or template is admin/manager.
do $$
declare t text;
begin
  foreach t in array array['flow_pipelines', 'flow_steps', 'flow_edges', 'flow_attachments', 'flow_templates'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "flow staff read" on public.%I for select to authenticated using ((select public.app_is_staff()))', t);
    execute format('create policy "flow staff insert" on public.%I for insert to authenticated with check ((select public.app_is_staff()))', t);
    execute format('create policy "flow staff update" on public.%I for update to authenticated using ((select public.app_is_staff())) with check ((select public.app_is_staff()))', t);
  end loop;
  foreach t in array array['flow_steps', 'flow_edges', 'flow_attachments'] loop
    execute format('create policy "flow staff delete" on public.%I for delete to authenticated using ((select public.app_is_staff()))', t);
  end loop;
  foreach t in array array['flow_pipelines', 'flow_templates'] loop
    execute format('create policy "flow managers delete" on public.%I for delete to authenticated using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.is_active is not false and p.role in (''admin'', ''manager'')))', t);
  end loop;
end $$;

