-- New pipeline (+ its template's steps and connections) in one transaction.
-- graph = {"steps":[{"key","kind","title","assignee","unit","x","y"}], "edges":[{"from","to","label"}]}
create or replace function public.flow_create(p jsonb, p_template uuid default null)
returns uuid language plpgsql security invoker set search_path = public as $$
declare v_id uuid; v_graph jsonb; v_s jsonb; v_e jsonb; v_map jsonb := '{}'::jsonb; v_step uuid; v_pieces int;
begin
  if coalesce(btrim(p->>'title'), '') = '' then raise exception 'Give the pipeline a name' using errcode = '23514'; end if;
  v_pieces := nullif(p->>'pieces', '')::int;
  insert into flow_pipelines (title, sku, pieces, sizes, costing_product_id, due_date, notes)
  values (btrim(p->>'title'), nullif(upper(btrim(coalesce(p->>'sku', ''))), ''), v_pieces, nullif(btrim(coalesce(p->>'sizes', '')), ''),
          nullif(p->>'costing_product_id', '')::uuid, nullif(p->>'due_date', '')::date, nullif(btrim(coalesce(p->>'notes', '')), ''))
  returning id into v_id;
  if p_template is not null then
    select graph into v_graph from flow_templates where id = p_template;
    if v_graph is null then raise exception 'That template no longer exists'; end if;
    for v_s in select value from jsonb_array_elements(coalesce(v_graph->'steps', '[]'::jsonb)) loop
      insert into flow_steps (pipeline_id, kind, title, assignee, unit, qty_planned, x, y)
      values (v_id, v_s->>'kind', coalesce(v_s->>'title', ''), nullif(v_s->>'assignee', ''), nullif(v_s->>'unit', ''),
              case when coalesce(v_s->>'unit', 'pcs') = 'pcs' then v_pieces end,
              coalesce((v_s->>'x')::int, 0), coalesce((v_s->>'y')::int, 0))
      returning id into v_step;
      v_map := v_map || jsonb_build_object(v_s->>'key', v_step);
    end loop;
    for v_e in select value from jsonb_array_elements(coalesce(v_graph->'edges', '[]'::jsonb)) loop
      if v_map ? (v_e->>'from') and v_map ? (v_e->>'to') then
        insert into flow_edges (pipeline_id, from_step, to_step, label)
        values (v_id, (v_map->>(v_e->>'from'))::uuid, (v_map->>(v_e->>'to'))::uuid, nullif(v_e->>'label', ''));
      end if;
    end loop;
  end if;
  return v_id;
end $$;
revoke all on function public.flow_create(jsonb, uuid) from public, anon;
grant execute on function public.flow_create(jsonb, uuid) to authenticated;

